CREATE TABLE IF NOT EXISTS inventory_snapshot_capture (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outlet_id BIGINT NOT NULL,
    business_date DATE NOT NULL,
    captured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expected_products INTEGER NOT NULL,
    recorded_products INTEGER NOT NULL DEFAULT 0,
    quantity_products INTEGER NOT NULL DEFAULT 0,
    capture_status VARCHAR(16) NOT NULL DEFAULT 'CAPTURING',
    CONSTRAINT uq_inventory_snapshot_capture UNIQUE (outlet_id, business_date)
);

CREATE TABLE IF NOT EXISTS inventory_daily_snapshot (
    outlet_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    business_date DATE NOT NULL,
    quantity DECIMAL(14,4) NULL,
    on_order DECIMAL(14,4) NOT NULL DEFAULT 0,
    captured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (outlet_id, product_id, business_date)
);

CREATE INDEX IF NOT EXISTS idx_inventory_daily_snapshot_date
    ON inventory_daily_snapshot (outlet_id, business_date);
