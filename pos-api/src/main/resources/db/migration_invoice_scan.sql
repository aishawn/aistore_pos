-- Supplier invoice OCR workspace linked only to native Orithos purchasing.
CREATE TABLE IF NOT EXISTS invoice_scan_session (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id BIGINT NOT NULL,
  created_by BIGINT NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'draft',
  source_type VARCHAR(16) NOT NULL DEFAULT 'upload',
  supplier_name VARCHAR(255) NULL,
  supplier_abn VARCHAR(64) NULL,
  invoice_number VARCHAR(128) NULL,
  invoice_date DATE NULL,
  due_date DATE NULL,
  total_payable DECIMAL(14, 2) NULL,
  gst_included DECIMAL(14, 2) NULL,
  supplier_id BIGINT NULL,
  outlet_id BIGINT NULL,
  purchase_order_id BIGINT NULL,
  purchase_order_name VARCHAR(128) NULL,
  receipt_id BIGINT NULL,
  receipt_name VARCHAR(128) NULL,
  source_filename VARCHAR(255) NULL,
  source_content_type VARCHAR(128) NULL,
  notes TEXT NULL,
  internal_notes TEXT NULL,
  ocr_json JSONB NULL,
  confirmed_by BIGINT NULL,
  confirmed_at TIMESTAMP NULL,
  discarded_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);

ALTER TABLE invoice_scan_session ADD COLUMN IF NOT EXISTS supplier_id BIGINT NULL;
ALTER TABLE invoice_scan_session ADD COLUMN IF NOT EXISTS outlet_id BIGINT NULL;
ALTER TABLE invoice_scan_session ADD COLUMN IF NOT EXISTS purchase_order_id BIGINT NULL;
ALTER TABLE invoice_scan_session ADD COLUMN IF NOT EXISTS purchase_order_name VARCHAR(128) NULL;
ALTER TABLE invoice_scan_session ADD COLUMN IF NOT EXISTS receipt_id BIGINT NULL;
ALTER TABLE invoice_scan_session ADD COLUMN IF NOT EXISTS receipt_name VARCHAR(128) NULL;

CREATE TABLE IF NOT EXISTS invoice_scan_line (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL,
  line_index INT NOT NULL DEFAULT 0,
  description VARCHAR(512) NULL,
  brand VARCHAR(255) NULL,
  pack_qty DECIMAL(14, 4) NULL,
  qty_cases DECIMAL(14, 4) NULL,
  unit_price DECIMAL(14, 4) NULL,
  line_total DECIMAL(14, 4) NULL,
  product_id BIGINT NULL,
  product_name VARCHAR(512) NULL,
  match_status VARCHAR(32) NOT NULL DEFAULT 'unmatched',
  confidence DECIMAL(6, 4) NULL,
  CONSTRAINT fk_invoice_scan_line_session
    FOREIGN KEY (session_id) REFERENCES invoice_scan_session (id) ON DELETE CASCADE
);

ALTER TABLE invoice_scan_line ADD COLUMN IF NOT EXISTS product_id BIGINT NULL;
ALTER TABLE invoice_scan_line ADD COLUMN IF NOT EXISTS product_name VARCHAR(512) NULL;

CREATE TABLE IF NOT EXISTS invoice_supplier_abn_map (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id BIGINT NOT NULL,
  supplier_abn VARCHAR(64) NOT NULL,
  supplier_id BIGINT NOT NULL,
  supplier_name VARCHAR(255) NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_invoice_supplier_abn UNIQUE (vendor_id, supplier_abn)
);

ALTER TABLE invoice_supplier_abn_map ADD COLUMN IF NOT EXISTS supplier_id BIGINT NULL;
