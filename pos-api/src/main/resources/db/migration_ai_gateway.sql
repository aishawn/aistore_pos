CREATE TABLE IF NOT EXISTS ai_gateway_usage (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id BIGINT NOT NULL,
  outlet_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  task VARCHAR(32) NOT NULL,
  provider VARCHAR(64) NOT NULL,
  model VARCHAR(128) NOT NULL,
  input_tokens INTEGER,
  output_tokens INTEGER,
  usage_reported BOOLEAN NOT NULL DEFAULT FALSE,
  latency_ms BIGINT NOT NULL,
  fallback BOOLEAN NOT NULL DEFAULT FALSE,
  request_status VARCHAR(16) NOT NULL,
  correlation_id VARCHAR(128),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ai_gateway_usage_scope_time
  ON ai_gateway_usage(vendor_id, outlet_id, created_at DESC);
