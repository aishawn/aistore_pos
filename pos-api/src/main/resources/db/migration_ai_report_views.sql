-- AI report views for template SQL / SqlGuard. Safe to re-run (CREATE OR REPLACE).
-- Cost columns are intentionally omitted; do not GRANT base tables to orithos_ai_ro.

-- Completed sale lines. Tenant is sale.outlet_id (not register / machine id).
CREATE OR REPLACE VIEW ai_rpt_sale_item AS
SELECT
  si.id,
  COALESCE(s.outlet_id, si.outlet_id) AS outlet_id,
  COALESCE(s.local_sold_at, s.created_at) AS sold_at,
  si.product_id,
  si.quantity AS qty,
  si.total_price AS amount,
  s.customer_id,
  s.id AS sale_id,
  COALESCE(s.business_date, DATE(COALESCE(s.local_sold_at, s.created_at))) AS business_date
FROM sale_item si
INNER JOIN sale s ON s.id = si.sale_id
WHERE s.status = 'COMPLETED';

-- Product names and category; no purchase cost.
CREATE OR REPLACE VIEW ai_rpt_product AS
SELECT
  p.id,
  p.outlet_id,
  p.name,
  p.status,
  p.category_id,
  c.name AS category_name,
  price.list_price,
  barcode.codes AS barcode,
  price.sale_quantity
FROM product p
LEFT JOIN category c ON c.id = p.category_id
LEFT JOIN LATERAL (
  SELECT pp.price AS list_price, pp.quantity AS sale_quantity
  FROM product_price pp
  WHERE pp.product_id = p.id AND pp.outlet_id = p.outlet_id
  ORDER BY pp.quantity, pp.id
  LIMIT 1
) price ON TRUE
LEFT JOIN LATERAL (
  SELECT STRING_AGG(pb.code, ' ' ORDER BY pb.code) AS codes
  FROM product_barcode pb
  WHERE pb.product_id = p.id AND pb.outlet_id = p.outlet_id
) barcode ON TRUE
WHERE p.deleted_at IS NULL;

-- Minimal product fields for count-only questions; avoid evaluating price/barcode joins.
CREATE OR REPLACE VIEW ai_rpt_product_count AS
SELECT p.id, p.outlet_id, p.status, p.name
FROM product p
WHERE p.deleted_at IS NULL;

-- Product identity fields without price/barcode lateral joins.
CREATE OR REPLACE VIEW ai_rpt_product_core AS
SELECT p.id, p.outlet_id, p.name, p.status
FROM product p
WHERE p.deleted_at IS NULL;

-- Lightweight exact/contains barcode lookup for bounded product search.
CREATE OR REPLACE VIEW ai_rpt_product_barcode AS
SELECT pb.product_id, pb.outlet_id, pb.code
FROM product_barcode pb;

-- On-hand inventory by outlet.
CREATE OR REPLACE VIEW ai_rpt_inventory AS
SELECT
  pi.product_id,
  pi.outlet_id,
  pi.quantity,
  pi.reorder_level,
  pi.on_order,
  pi.updated_at
FROM product_inventory pi;

-- Cost is exposed through a separately guarded view. Application report and
-- SQL guard permissions must authorize access before this view is queried.
CREATE OR REPLACE VIEW ai_rpt_inventory_cost AS
SELECT
    p.id AS product_id,
    p.outlet_id,
    (CASE WHEN p.cost_percentage <> 0 THEN NULL ELSE
        COALESCE(pc.average_cost, pc.cost,
            CASE WHEN p.shopfront_source_updated_at IS NULL OR p.case_cost IS NOT NULL
                 THEN p.cost END)
    END)::NUMERIC(14,4) AS cost,
    CASE WHEN p.cost_percentage <> 0 THEN NULL ELSE p.case_cost END AS case_cost,
    p.case_quantity
FROM product p
LEFT JOIN product_cost pc ON pc.product_id = p.id AND pc.outlet_id = p.outlet_id;

-- One row per completed sale (average ticket / customer-sale).
CREATE OR REPLACE VIEW ai_rpt_customer_sale AS
SELECT
  s.id AS sale_id,
  s.outlet_id AS outlet_id,
  COALESCE(s.local_sold_at, s.created_at) AS sold_at,
  s.customer_id,
  s.total_price AS amount,
  COALESCE(s.business_date, DATE(COALESCE(s.local_sold_at, s.created_at))) AS business_date
FROM sale s
WHERE s.status = 'COMPLETED';

-- NL2SQL / template audit (question, generated SQL, allow/deny).
CREATE TABLE IF NOT EXISTS ai_report_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  outlet_id BIGINT NULL,
  outlet_ids VARCHAR(255) NULL,
  question TEXT NULL,
  sql_text TEXT NULL,
  path VARCHAR(32) NULL,
  allowed BOOLEAN NOT NULL DEFAULT FALSE,
  reject_reason VARCHAR(512) NULL,
  row_count INT NULL,
  latency_ms INT NULL,
  estimated_tokens INT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
