CREATE TABLE IF NOT EXISTS ai_decision_snapshot (
  id UUID PRIMARY KEY,
  vendor_id BIGINT NOT NULL,
  outlet_id BIGINT NOT NULL,
  decision_type VARCHAR(32) NOT NULL CHECK (decision_type IN ('PRICING', 'REPLENISHMENT')),
  source_system VARCHAR(32) NOT NULL,
  source_version VARCHAR(128) NOT NULL,
  data_as_of TIMESTAMPTZ NOT NULL,
  computed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  config_version VARCHAR(128) NOT NULL,
  model_version VARCHAR(128),
  status VARCHAR(32) NOT NULL,
  decision_json JSONB NOT NULL,
  data_quality_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ai_decision_scope_time
  ON ai_decision_snapshot(vendor_id, outlet_id, decision_type, computed_at DESC);

CREATE TABLE IF NOT EXISTS ai_decision_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id UUID NOT NULL REFERENCES ai_decision_snapshot(id),
  vendor_id BIGINT NOT NULL,
  outlet_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  action VARCHAR(32) NOT NULL CHECK (action IN ('ACCEPTED', 'ADJUSTED', 'REJECTED', 'EXECUTED', 'READBACK_MISMATCH')),
  before_json JSONB,
  after_json JSONB,
  note TEXT,
  correlation_id VARCHAR(128),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ai_decision_audit_scope_time
  ON ai_decision_audit(vendor_id, outlet_id, snapshot_id, created_at DESC);

-- Historical Odoo snapshots are intentionally retired; live AI reads use Orithos tables.
DROP TABLE IF EXISTS odoo_read_snapshot;
