CREATE TABLE IF NOT EXISTS ai_command_draft (
  id UUID PRIMARY KEY,
  vendor_id BIGINT NOT NULL,
  outlet_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  command_type VARCHAR(64) NOT NULL,
  status VARCHAR(32) NOT NULL,
  source_text TEXT NOT NULL,
  source_thread_id VARCHAR(255),
  confidence DECIMAL(6,5) NOT NULL DEFAULT 0,
  expires_at TIMESTAMP NOT NULL,
  command_version VARCHAR(64) NOT NULL,
  items_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  excluded_items_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  changes_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  idempotency_key VARCHAR(128) NOT NULL UNIQUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ai_command_scope ON ai_command_draft(vendor_id, outlet_id, user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS ai_command_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  command_id UUID NOT NULL,
  vendor_id BIGINT NOT NULL,
  outlet_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  event_type VARCHAR(32) NOT NULL,
  from_status VARCHAR(32),
  to_status VARCHAR(32),
  confirmation_mode VARCHAR(16),
  result_json JSONB,
  correlation_id VARCHAR(128),
  source_commit VARCHAR(64),
  runtime_commit VARCHAR(64),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ai_command_audit_scope ON ai_command_audit(vendor_id, outlet_id, created_at DESC);

CREATE TABLE IF NOT EXISTS ai_decision_snapshot (
  id UUID PRIMARY KEY,
  vendor_id BIGINT NOT NULL,
  outlet_id BIGINT NOT NULL,
  decision_type VARCHAR(32) NOT NULL CHECK (decision_type IN ('PRICING', 'REPLENISHMENT')),
  source_system VARCHAR(32) NOT NULL,
  source_version VARCHAR(128) NOT NULL,
  data_as_of TIMESTAMPTZ NOT NULL,
  computed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  config_version VARCHAR(128) NOT NULL,
  model_version VARCHAR(128),
  status VARCHAR(32) NOT NULL,
  decision_json JSONB NOT NULL,
  data_quality_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ai_decision_scope_time
  ON ai_decision_snapshot(vendor_id, outlet_id, decision_type, computed_at DESC);

CREATE TABLE IF NOT EXISTS ai_decision_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id UUID NOT NULL REFERENCES ai_decision_snapshot(id),
  vendor_id BIGINT NOT NULL,
  outlet_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  action VARCHAR(32) NOT NULL CHECK (action IN ('ACCEPTED', 'ADJUSTED', 'REJECTED', 'EXECUTED', 'READBACK_MISMATCH')),
  before_json JSONB,
  after_json JSONB,
  note TEXT,
  correlation_id VARCHAR(128),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ai_decision_audit_scope_time
  ON ai_decision_audit(vendor_id, outlet_id, snapshot_id, created_at DESC);

CREATE TABLE IF NOT EXISTS odoo_read_snapshot (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id BIGINT NOT NULL,
  outlet_id BIGINT NOT NULL,
  object_type VARCHAR(32) NOT NULL CHECK (object_type IN ('PRODUCT', 'SALE_LINE', 'INVENTORY', 'PRICE', 'SUPPLIER', 'PURCHASE_LINE')),
  source_record_id VARCHAR(128) NOT NULL,
  source_version VARCHAR(128),
  event_time TIMESTAMPTZ,
  ingested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  data_quality_status VARCHAR(32) NOT NULL DEFAULT 'VALID',
  payload JSONB NOT NULL,
  UNIQUE (vendor_id, outlet_id, object_type, source_record_id, ingested_at)
);
CREATE INDEX IF NOT EXISTS idx_odoo_snapshot_latest
  ON odoo_read_snapshot(vendor_id, outlet_id, object_type, ingested_at DESC);
