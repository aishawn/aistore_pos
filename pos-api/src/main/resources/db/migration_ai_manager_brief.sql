CREATE TABLE IF NOT EXISTS ai_manager_daily_brief (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id BIGINT NOT NULL,
  outlet_id BIGINT NOT NULL,
  business_date DATE NOT NULL,
  revision INT NOT NULL,
  timezone VARCHAR(64) NOT NULL,
  data_as_of TIMESTAMP WITH TIME ZONE NULL,
  data_quality VARCHAR(24) NOT NULL,
  payload_json TEXT NOT NULL,
  model_status VARCHAR(24) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (vendor_id, outlet_id, business_date, revision)
);

CREATE INDEX IF NOT EXISTS idx_ai_manager_daily_brief_latest
  ON ai_manager_daily_brief (vendor_id, outlet_id, business_date, revision DESC);

CREATE TABLE IF NOT EXISTS ai_manager_daily_brief_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brief_id BIGINT NOT NULL REFERENCES ai_manager_daily_brief(id),
  vendor_id BIGINT NOT NULL,
  outlet_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  card_id VARCHAR(96) NULL,
  event_type VARCHAR(24) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ai_manager_daily_brief_event_actor
  ON ai_manager_daily_brief_event (vendor_id, outlet_id, user_id, created_at DESC);
