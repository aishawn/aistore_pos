CREATE TABLE IF NOT EXISTS purchase_receipt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id BIGINT NOT NULL,
    order_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    idempotency_key VARCHAR(200) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    status VARCHAR(24) NOT NULL,
    received_by_id BIGINT NULL,
    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (vendor_id, idempotency_key)
);
CREATE INDEX IF NOT EXISTS idx_purchase_receipt_order ON purchase_receipt(vendor_id, order_id, received_at);

CREATE TABLE IF NOT EXISTS purchase_receipt_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id BIGINT NOT NULL,
    order_product_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    received_quantity DECIMAL(14,4) NOT NULL,
    inventory_quantity DECIMAL(14,4) NOT NULL,
    unit_cost DECIMAL(14,4) NULL,
    UNIQUE (receipt_id, order_product_id)
);

CREATE TABLE IF NOT EXISTS purchase_receipt_batch (
    receipt_line_id BIGINT NOT NULL REFERENCES purchase_receipt_line(id),
    batch_code VARCHAR(120) NOT NULL,
    expiry_date DATE NOT NULL,
    inventory_quantity DECIMAL(14,4) NOT NULL CHECK (inventory_quantity > 0),
    PRIMARY KEY (receipt_line_id, batch_code)
);

CREATE TABLE IF NOT EXISTS inventory_movement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity_delta DECIMAL(14,4) NOT NULL,
    source_type VARCHAR(32) NOT NULL,
    source_id BIGINT NOT NULL,
    source_line_id BIGINT NOT NULL,
    idempotency_key VARCHAR(200) NOT NULL,
    actor_id BIGINT NULL,
    occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (source_type, source_line_id)
);
CREATE INDEX IF NOT EXISTS idx_inventory_movement_scope ON inventory_movement(vendor_id, outlet_id, product_id, occurred_at);

CREATE TABLE IF NOT EXISTS sale_checkout_idempotency (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id BIGINT NOT NULL,
    idempotency_key VARCHAR(200) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    response_json TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (vendor_id, idempotency_key)
);
