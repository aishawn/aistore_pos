    CONSTRAINT ck_competitor_member_price CHECK (member_price IS NULL OR member_price > 0),
    CONSTRAINT ck_competitor_unit_price_basis CHECK (unit_price_basis IN ('PER_UNIT', 'PER_LITRE')),
    CONSTRAINT ck_competitor_pack_size CHECK (pack_size > 0),
    CONSTRAINT ck_competitor_price_type CHECK (price_type IN ('STANDARD', 'PROMOTION', 'MULTIBUY', 'MEMBER', 'CLEARANCE')),
