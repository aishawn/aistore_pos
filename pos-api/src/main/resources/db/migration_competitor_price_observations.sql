CREATE TABLE IF NOT EXISTS vendor_competitor_source_permission (
    vendor_id BIGINT NOT NULL,
    source_id BIGINT NOT NULL REFERENCES competitor_price_source(id),
    access_mode VARCHAR(24) NOT NULL DEFAULT 'UNREVIEWED',
    terms_url VARCHAR(1024) NULL,
    terms_reviewed_at TIMESTAMP NULL,
    terms_reviewed_by BIGINT NULL,
    review_summary TEXT NOT NULL DEFAULT '',
    permitted_fields TEXT NOT NULL DEFAULT '',
    retention_terms TEXT NOT NULL DEFAULT '',
    rate_limit_terms VARCHAR(512) NOT NULL DEFAULT '',
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (vendor_id, source_id),
    CONSTRAINT ck_vendor_competitor_access_mode CHECK (access_mode IN ('UNREVIEWED', 'MANUAL_ONLY', 'BLOCKED')),
    CONSTRAINT ck_vendor_competitor_permission_evidence CHECK (
      access_mode <> 'MANUAL_ONLY' OR (
        terms_url IS NOT NULL AND terms_reviewed_at IS NOT NULL AND terms_reviewed_by IS NOT NULL
        AND BTRIM(review_summary) <> '' AND BTRIM(permitted_fields) <> ''
        AND BTRIM(retention_terms) <> '' AND BTRIM(rate_limit_terms) <> ''
      )
    )
);

