    CONSTRAINT ck_competitor_match_confidence CHECK (match_confidence >= 0 AND match_confidence <= 1),
    CONSTRAINT ck_competitor_capture_method CHECK (capture_method IN ('MANUAL', 'AUTHORIZED_API', 'LICENSED_FEED')),
    CONSTRAINT ck_competitor_match_method CHECK (match_method IN ('EAN', 'ATTRIBUTE', 'MANUAL')),
    CONSTRAINT ck_competitor_review_status CHECK (review_status IN ('PENDING_REVIEW', 'VERIFIED', 'REJECTED')),
    CONSTRAINT ck_competitor_match_review_status CHECK (match_review_status IN ('PENDING', 'PASS', 'FAIL')),
    CONSTRAINT ck_competitor_price_review_status CHECK (price_review_status IN ('PENDING', 'PASS', 'FAIL')),
    CONSTRAINT ck_competitor_verified_facets CHECK (review_status <> 'VERIFIED' OR (match_review_status = 'PASS' AND price_review_status = 'PASS'))
);

