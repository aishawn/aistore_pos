    volume_ml INTEGER NULL,
    vintage VARCHAR(16) NULL,
    pack_size INTEGER NOT NULL DEFAULT 1,
    price_type VARCHAR(24) NOT NULL DEFAULT 'STANDARD',
    price_tax_basis VARCHAR(24) NOT NULL DEFAULT 'INCLUDES_GST',
    observed_price DECIMAL(14,4) NOT NULL,
    member_price DECIMAL(14,4) NULL,
    unit_price DECIMAL(14,4) NULL,
    unit_price_basis VARCHAR(24) NOT NULL DEFAULT 'PER_UNIT',
    promotion_terms VARCHAR(512) NULL,
    promotion_starts_at TIMESTAMP NULL,
    promotion_ends_at TIMESTAMP NULL,
    postcode VARCHAR(12) NOT NULL,
    fulfillment VARCHAR(24) NOT NULL,
    source_url VARCHAR(1024) NOT NULL,
