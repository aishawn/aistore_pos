-- Phase A: DB-backed AI intents, slots, prompts (add/remove without code change)
-- Run once against the PostgreSQL orithos database.

CREATE TABLE IF NOT EXISTS ai_intent (
  id           BIGINT       GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  code         VARCHAR(64)  NOT NULL,
  name         VARCHAR(128) NOT NULL,
  description  VARCHAR(512) NULL,
  prompt_hint  VARCHAR(1024) NULL,
  default_panel VARCHAR(32) NULL,
  default_view  VARCHAR(32) NULL,
  enabled      SMALLINT   NOT NULL DEFAULT 1,
  sort_order   INT          NOT NULL DEFAULT 0,
  created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_ai_intent_code UNIQUE (code)
);
CREATE TABLE IF NOT EXISTS ai_slot (
  id           BIGINT       GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  code         VARCHAR(64)  NOT NULL,
  name         VARCHAR(128) NOT NULL,
  description  VARCHAR(512) NULL,
  value_type   VARCHAR(32)  NOT NULL DEFAULT 'string',
  max_length   INT          NOT NULL DEFAULT 100,
  enabled      SMALLINT   NOT NULL DEFAULT 1,
  sort_order   INT          NOT NULL DEFAULT 0,
  created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_ai_slot_code UNIQUE (code)
);
CREATE TABLE IF NOT EXISTS ai_slot_value (
  id           BIGINT       GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  slot_code    VARCHAR(64)  NOT NULL,
  value_key    VARCHAR(128) NOT NULL,
  value        VARCHAR(512) NOT NULL,
  label        VARCHAR(128) NULL,
  enabled      SMALLINT   NOT NULL DEFAULT 1,
  sort_order   INT          NOT NULL DEFAULT 0,
  created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_ai_slot_value UNIQUE (slot_code, value_key));
CREATE TABLE IF NOT EXISTS ai_prompt (
  id           BIGINT       GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  code         VARCHAR(64)  NOT NULL,
  name         VARCHAR(128) NOT NULL,
  content      TEXT         NOT NULL,
  enabled      SMALLINT   NOT NULL DEFAULT 1,
  updated_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_ai_prompt_code UNIQUE (code)
);
