package com.orithos.config;

import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
@Order(32)
public class SaleCheckoutIdempotencySchemaMigrator implements CommandLineRunner {
    private final JdbcTemplate jdbc;

    public SaleCheckoutIdempotencySchemaMigrator(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @Override
    public void run(String... args) {
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS sale_checkout_idempotency (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    vendor_id BIGINT NOT NULL,
                    idempotency_key VARCHAR(200) NOT NULL,
                    request_hash VARCHAR(64) NOT NULL,
                    response_json TEXT NOT NULL,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE (vendor_id, idempotency_key)
                )
                """);
    }
}
