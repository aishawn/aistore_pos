package com.orithos.config;

import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
@Order(33)
public class RegisterSessionSchemaMigrator implements CommandLineRunner {
    private final JdbcTemplate jdbc;

    public RegisterSessionSchemaMigrator(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @Override
    public void run(String... args) {
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS register_session (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    vendor_id BIGINT NOT NULL,
                    outlet_id BIGINT NOT NULL,
                    register_id BIGINT NOT NULL REFERENCES register(id),
                    opened_by BIGINT NOT NULL,
                    opened_at TIMESTAMP NOT NULL,
                    opening_float NUMERIC(14, 2) NOT NULL CHECK (opening_float >= 0),
                    open_idempotency_key VARCHAR(200) NOT NULL,
                    closed_at TIMESTAMP NULL,
                    closure_id BIGINT NULL,
                    close_idempotency_key VARCHAR(200) NULL,
                    UNIQUE (register_id, open_idempotency_key),
                    UNIQUE (register_id, close_idempotency_key)
                )
                """);
        jdbc.execute("CREATE UNIQUE INDEX IF NOT EXISTS uq_register_session_active ON register_session(register_id) WHERE closed_at IS NULL");
        jdbc.execute("ALTER TABLE register_session ADD COLUMN IF NOT EXISTS close_request_hash VARCHAR(64)");
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS register_cash_movement (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    session_id BIGINT NOT NULL REFERENCES register_session(id),
                    vendor_id BIGINT NOT NULL,
                    outlet_id BIGINT NOT NULL,
                    register_id BIGINT NOT NULL,
                    user_id BIGINT NOT NULL,
                    movement_type VARCHAR(24) NOT NULL CHECK (movement_type IN ('CASH_IN', 'CASH_OUT')),
                    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
                    reason TEXT NOT NULL,
                    idempotency_key VARCHAR(200) NOT NULL,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE (session_id, idempotency_key)
                )
                """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS ix_register_cash_movement_session ON register_cash_movement(session_id, created_at)");
    }
}
